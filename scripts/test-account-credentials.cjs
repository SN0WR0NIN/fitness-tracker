const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const bcrypt = require('bcryptjs');
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, esModuleInterop: true } }).outputText, filename);
let account;
let attempts;
const prismaPath = require.resolve('../src/lib/prisma.ts');
require.cache[prismaPath] = { id: prismaPath, filename: prismaPath, loaded: true, exports: { prisma: { $transaction: async (fn) => fn({ user: { findMany: async () => account ? [account] : [], update: async () => { attempts++; } } }) } } };
const { verifyCredentials, UsernameSchema, NewPasswordSchema, ContactEmailSchema } = require('../src/lib/account-credentials.ts');
(async () => {
  assert.equal(UsernameSchema.parse(' Athlete.1 '), 'athlete.1');
  assert.equal(UsernameSchema.safeParse('person@example.com').success, false);
  assert.equal(NewPasswordSchema.safeParse('short').success, false);
  assert.equal(NewPasswordSchema.safeParse('💪'.repeat(30)).success, false);
  assert.equal(ContactEmailSchema.safeParse('test@participants.invalid').success, false);
  account = { id: 'test', password: await bcrypt.hash('TemporaryPassword123', 4), mustChangePassword: true, temporaryPasswordExpiresAt: new Date(Date.now() + 60000), loginAttempts: 0, loginWindowStartedAt: null };
  attempts = 0;
  assert.equal((await verifyCredentials('athlete', 'TemporaryPassword123')).id, 'test');
  assert.equal(await verifyCredentials('athlete', 'wrong'), null);
  assert.equal(attempts, 2);
  account.temporaryPasswordExpiresAt = new Date(0);
  assert.equal(await verifyCredentials('athlete', 'TemporaryPassword123'), null);
  account.mustChangePassword = false;
  assert.equal((await verifyCredentials('athlete', 'TemporaryPassword123')).id, 'test');
  account.loginWindowStartedAt = new Date(); account.loginAttempts = 10;
  assert.equal(await verifyCredentials('athlete', 'TemporaryPassword123'), null);
  account.password = '!UNCLAIMED'; account.loginAttempts = 0;
  assert.equal(await verifyCredentials('athlete', '!UNCLAIMED'), null);
  console.log('Credential validation, temporary expiry, attempt limits and unclaimed-account checks passed (mock database).');
})().catch((error) => { console.error(error); process.exitCode = 1; });
